#!/usr/bin/env python3
"""Deterministically generate the Experiments LaTeX tables from attack_multi.py eval.json files.

Deterministic: same JSONs in -> byte-identical .tex out. No timestamps, no glob ordering,
no randomness; every row/column/stratum is an explicit ordered list, fixed rounding. A missing
or incomplete source yields a '--' cell and a '% MISSING' comment, so the paper still builds.

  python tools/paper_tables.py --results-root . --out tools/paper_tables_out
Produces: hiding.tex, lidar_strata.tex, ghosts.tex

Edit the RESULTS manifest below to repoint a table at a newer run directory.
"""
