#!/usr/bin/env python3
"""Official nuScenes metrics table: clean vs 3-seed attacked (universal bbox texture).

Reads the mmdet3d NuScenesEval dumps (logs/attack/official_{clean,atk_s*}/*.json) and
emits a booktabs LaTeX table (clean, attacked mean+/-std over seeds, and the drop) plus a
plain-text summary.  Per-class AP is the mean over the {0.5,1,2,4} m matching thresholds.

Usage:
  python tools/official_table.py                       # autodiscover under logs/attack
  python tools/official_table.py --tex paper_overleaf/experiments/generated/official.tex
"""
import argparse
import glob
import json
import os
import numpy as np

NS = 'pts_bbox_NuScenes/'
THR = ('0.5', '1.0', '2.0', '4.0')
# rows: (latex label, key) -- 'class:car' means per-class AP averaged over thresholds
ROWS = [('mAP',        'mAP'),
        ('NDS',        'NDS'),
        ('Car AP',     'class:car'),
        ('Truck AP',   'class:truck'),
        ('Bus AP',     'class:bus')]


def metric(d, key):
    if key.startswith('class:'):
        c = key.split(':', 1)[1]
        return float(np.mean([d[f'{NS}{c}_AP_dist_{t}'] for t in THR]))
    return float(d[f'{NS}{key}'])


def find(base):
    clean = sorted(glob.glob(os.path.join(base, 'official_clean*', 'official_clean.json')))
    atks = sorted(glob.glob(os.path.join(base, 'official_atk_s*', 'official_attack.json')))
    return clean, atks


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--base', default='/home/tkg5kq/workdir/av_project/multifusion_mask/logs/attack')
    ap.add_argument('--clean', default=None)
    ap.add_argument('--attack', nargs='*', default=None)
    ap.add_argument('--tex', default=None, help='write LaTeX table here')
    args = ap.parse_args()

    clean_paths, atk_paths = find(args.base)
    if args.clean:
        clean_paths = [args.clean]
    if args.attack:
        atk_paths = args.attack
    if not clean_paths or not atk_paths:
        raise SystemExit(f'missing JSONs (clean={clean_paths}, attack={atk_paths})')

    cd = json.load(open(clean_paths[0]))
    ads = [json.load(open(p)) for p in atk_paths]
    nseed = len(ads)

    rows = []
    for label, key in ROWS:
        c = metric(cd, key)
        a = np.array([metric(d, key) for d in ads])
        rows.append((label, c, a.mean(), a.std(ddof=1) if nseed > 1 else 0.0))

    # plain-text
    print(f'clean: {os.path.relpath(clean_paths[0], args.base)}')
    print(f'attacked seeds ({nseed}): ' + ', '.join(os.path.relpath(p, args.base).split("/")[0] for p in atk_paths))
    print(f'\n{"metric":10s} {"clean":>7} {"attacked":>16} {"drop":>8}')
    print('-' * 44)
    for label, c, mu, sd in rows:
        print(f'{label:10s} {c:7.3f} {mu:8.3f} +/- {sd:5.3f}   {mu - c:+7.3f}')

    # LaTeX
    tex = []
    tex.append('% auto-generated by tools/official_table.py')
    tex.append('\\begin{tabular}{lccc}')
    tex.append('\\toprule')
    tex.append(f'Metric & Clean & Attacked ({nseed} seeds) & $\\Delta$ \\\\')
    tex.append('\\midrule')
    for i, (label, c, mu, sd) in enumerate(rows):
        bold = label in ('mAP', 'NDS')
        lab = f'\\textbf{{{label}}}' if bold else label
        tex.append(f'{lab} & {c:.3f} & ${mu:.3f} \\pm {sd:.3f}$ & ${mu - c:+.3f}$ \\\\')
        if i == 1:
            tex.append('\\midrule')
    tex.append('\\bottomrule')
    tex.append('\\end{tabular}')
    tex = '\n'.join(tex) + '\n'

    if args.tex:
        os.makedirs(os.path.dirname(os.path.abspath(args.tex)), exist_ok=True)
        with open(args.tex, 'w') as fh:
            fh.write(tex)
        print('\nwrote', args.tex)
    print('\n' + tex)


if __name__ == '__main__':
    main()
