#!/usr/bin/env python3
"""Aggregate the N-vehicle ghost dose-response sweep.

Walks logs/attack/nsweep_<JOB>/n<N>_s<S>/eval.json and reports fabricated
("ghost") detections per scene as a function of N (number of painted vehicles),
averaged over the random seeds.

Ghosts are the learned-attack false positives minus the clean-scene false
positives in the same BEV zone (so we credit only what the attack adds):
    net = fp[learned][zone].per_scene - fp[clean][zone].per_scene
The convex hull needs >=3 painted vehicles, so for N=1,2 the 'hull' zone is 0 by
construction -- we therefore headline 'hull+ring' (ghosts in and immediately
around the painted set), which is defined for every N.

Usage:
  python tools/agg_nsweep.py logs/attack/nsweep_22196457   # a sweep dir
  python tools/agg_nsweep.py                                # newest nsweep_* dir
Optional: --tex tools/../paper_overleaf/experiments/generated/nsweep.tex
"""
import argparse
import glob
import json
import os
import re
import numpy as np

ZONES = ('hull', 'ring', 'elsewhere')


def net_ghosts(fp):
    """Return dict zone->net per-scene ghosts (learned minus clean), plus hull+ring."""
    out = {}
    for z in ZONES:
        lp = fp.get('learned', {}).get(z, {}).get('per_scene', 0.0)
        cp = fp.get('clean', {}).get(z, {}).get('per_scene', 0.0)
        out[z] = lp - cp
    out['hull+ring'] = out['hull'] + out['ring']
    return out


def load_sweep(root):
    """root/n<N>_s<S>/eval.json -> {N: {seed: netghosts, 'raw_learned_hullring':...}}."""
    by_n = {}
    for path in sorted(glob.glob(os.path.join(root, 'n*_s*', 'eval.json'))):
        m = re.search(r'/n(\d+)_s(\d+)/eval\.json$', path)
        if not m:
            continue
        n, s = int(m.group(1)), int(m.group(2))
        try:
            d = json.load(open(path))
            fp = d['extra']['false_positives']
        except (json.JSONDecodeError, KeyError, OSError) as e:
            print(f'  [skip] {path}: {e}')
            continue
        ng = net_ghosts(fp)
        # also keep raw learned hull+ring (not clean-subtracted) for context
        ng['_raw_hullring'] = (fp.get('learned', {}).get('hull', {}).get('per_scene', 0.0)
                               + fp.get('learned', {}).get('ring', {}).get('per_scene', 0.0))
        by_n.setdefault(n, {})[s] = ng
    return by_n


def msd(vals):
    a = np.asarray(vals, float)
    return (a.mean(), a.std(ddof=1) if len(a) > 1 else 0.0, len(a))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('root', nargs='?', default=None, help='nsweep_<JOB> dir (default: newest)')
    ap.add_argument('--base', default='/home/tkg5kq/workdir/av_project/multifusion_mask/logs/attack')
    ap.add_argument('--tex', default=None, help='optional LaTeX table out path')
    args = ap.parse_args()

    root = args.root
    if root is None:
        cands = sorted(glob.glob(os.path.join(args.base, 'nsweep_*')), key=os.path.getmtime)
        if not cands:
            raise SystemExit('no nsweep_* dir found under ' + args.base)
        root = cands[-1]
    print('sweep dir:', root)

    by_n = load_sweep(root)
    if not by_n:
        raise SystemExit('no eval.json found yet (sweep still running or not started)')

    cols = ('hull', 'ring', 'hull+ring')
    print(f'\n{"N":>3} {"seeds":>6} | ' + ' | '.join(f'{c+" net/scene":>18}' for c in cols)
          + f' | {"raw hull+ring":>14}')
    print('-' * 86)
    rows = []
    for n in sorted(by_n):
        seeds = by_n[n]
        cell = []
        for c in cols:
            mu, sd, k = msd([seeds[s][c] for s in seeds])
            cell.append((mu, sd))
        rawmu = np.mean([seeds[s]['_raw_hullring'] for s in seeds])
        rows.append((n, len(seeds), cell, rawmu))
        cellstr = ' | '.join(f'{mu:7.2f} +/- {sd:5.2f}' for mu, sd in cell)
        print(f'{n:>3} {len(seeds):>6} | {cellstr} | {rawmu:>14.2f}')

    # dose-response read-out on hull+ring (the headline)
    ns = [r[0] for r in rows]
    hr = [r[2][2][0] for r in rows]  # hull+ring mean
    print('\ndose-response (hull+ring net ghosts/scene): ' +
          '  '.join(f'N={n}:{v:.2f}' for n, v in zip(ns, hr)))
    if len(ns) >= 2:
        slope = np.polyfit(ns, hr, 1)[0]
        print(f'linear slope: {slope:+.3f} ghosts/scene per added vehicle; '
              f'N=1 baseline: {hr[0]:.2f}')
        verdict = ('RISES with N -> multi-vehicle effect is real'
                   if slope > 0.1 and hr[0] < hr[-1] else
                   'FLAT/weak -> lean on hiding + official AP instead')
        print('verdict:', verdict)

    if args.tex:
        with open(args.tex, 'w') as fh:
            fh.write('% auto-generated by tools/agg_nsweep.py\n')
            fh.write('\\begin{tabular}{rccc}\n\\toprule\n')
            fh.write('$N$ & hull & ring & hull+ring \\\\\n\\midrule\n')
            for n, k, cell, _ in rows:
                fh.write(f'{n} & ' + ' & '.join(f'${mu:.2f}\\pm{sd:.2f}$' for mu, sd in cell)
                         + ' \\\\\n')
            fh.write('\\bottomrule\n\\end{tabular}\n')
        print('wrote', args.tex)


if __name__ == '__main__':
    main()
