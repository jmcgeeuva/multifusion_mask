#!/usr/bin/env python3
"""Cross-model transfer table: IS-Fusion-optimized camouflage evaluated on never-optimized
fusion detectors (BEVFusion now; TransFusion slots in as a second victim block).

Reads the decoupled nuScenes-metric job logs (scripts/bevfusion_metric.sh -> logs/transfer/
bevf_metric_<jobid>.out, each ending in a single `ALL METRICS: {...}` dict) and emits a
booktabs LaTeX table (same convention as tools/official_table.py) plus a plain-text echo.
Per-class AP is the mean over the {0.5,1,2,4} m matching thresholds; "Veh. mean" is the mean
of car/truck/bus AP (the painted classes). Deterministic: unchanged logs -> identical .tex.

To add a victim/condition, edit VICTIMS below (label -> metric-log job id). A condition whose
log is missing or lacks ALL METRICS is skipped with a warning, so the table renders with
whatever has completed.

Usage:
  python tools/transfer_table.py                                    # plain-text + default tex path
  python tools/transfer_table.py --tex paper_overleaf/experiments/generated/transfer.tex
"""
import argparse
import os
import re

# victim -> ordered conditions -> metric-log job id (logs/transfer/bevf_metric_<id>.out)
VICTIMS = {
    'BEVFusion': dict(
        dir='logs/transfer', pat='bevf_metric_{jid}.out',
        conds=[('Clean', '22231533'), ('Random paint', '22237648'),
               ('Transfer (single)', '22240642'), ('Transfer (multi)', '22237673'),
               ('Transfer (multi+nat)', '22237257')]),
    'CMT': dict(
        dir='/sfs/weka/scratch/tkg5kq/transfer/cmt/logs', pat='cmt_metric_{jid}.out',
        conds=[('Clean', '22242179'), ('Random paint', '22242981'),
               ('Transfer (single)', '22242983'), ('Transfer (multi)', '22242985'),
               ('Transfer (multi+nat)', '22242987')]),
}

THR = ('0.5', '1.0', '2.0', '4.0')
VEH = ('car', 'truck', 'bus')
# (latex label, metric key); 'class:<c>' = per-class AP mean over thresholds; 'veh' = car/truck/bus mean
ROWS = [('mAP',       'map'),
        ('NDS',       'nds'),
        ('Car AP',    'class:car'),
        ('Truck AP',  'class:truck'),
        ('Bus AP',    'class:bus'),
        ('Veh. mean', 'veh')]


def parse_metrics(path):
    """Read an `ALL METRICS: {...}` log and NORMALIZE to canonical keys (map, nds, <c>_ap).
    Handles both the BEVFusion-wrapper schema (object/map, object/<c>_ap_dist_<t>) and the
    CMT/official nuScenes schema (pts_bbox_NuScenes/mAP, .../<c>_AP_dist_<t>). Tolerant of
    `nan` tokens (not a valid Python literal)."""
    if not os.path.exists(path):
        return None
    txt = open(path).read()
    if 'ALL METRICS' not in txt:
        return None
    raw = {}
    for k, v in re.findall(r"'([^']+)':\s*([0-9.]+|nan)", txt):
        raw[k] = float('nan') if v == 'nan' else float(v)

    def g(*names):
        for n in names:
            if n in raw:
                return raw[n]
        return float('nan')

    out = {'map': g('object/map', 'pts_bbox_NuScenes/mAP'),
           'nds': g('object/nds', 'pts_bbox_NuScenes/NDS')}
    for c in VEH:
        vals = [g(f'object/{c}_ap_dist_{t}', f'pts_bbox_NuScenes/{c}_AP_dist_{t}') for t in THR]
        vals = [x for x in vals if x == x]          # drop nan
        out[f'{c}_ap'] = sum(vals) / len(vals) if vals else float('nan')
    return out


def metric(d, key):
    if key == 'veh':
        return sum(d[f'{c}_ap'] for c in VEH) / len(VEH)
    if key.startswith('class:'):
        return d[key.split(':', 1)[1] + '_ap']
    return d.get(key, float('nan'))


def load_victim(spec):
    out = []
    for label, jid in spec['conds']:
        d = parse_metrics(os.path.join(spec['dir'], spec['pat'].format(jid=jid)))
        if d is None:
            print(f'WARN: {label} (job {jid}) has no metrics yet; skipping column')
            continue
        out.append((label, d))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tex', default=None, help='write LaTeX table here')
    args = ap.parse_args()

    victims = {v: load_victim(spec) for v, spec in VICTIMS.items()}
    victims = {v: cols for v, cols in victims.items() if cols}
    if not victims:
        raise SystemExit('no completed metric logs found')

    tex = ['% auto-generated by tools/transfer_table.py -- do not edit by hand']
    for vi, (victim, cols) in enumerate(victims.items()):
        labels = [l for l, _ in cols]
        clean = dict(cols).get('Clean')

        # plain-text
        print(f'\n=== IS-Fusion -> {victim} transfer (nuScenes val) ===')
        print(f'{"metric":10s}' + ''.join(f'{l:>22s}' for l in labels))
        for rl, key in ROWS:
            print(f'{rl:10s}' + ''.join(f'{metric(d, key):22.3f}' for _, d in cols))
        if clean is not None:
            print(f'{"Δ Veh.":10s}' + ''.join(
                f'{(metric(d,"veh")-metric(clean,"veh")):+22.3f}' for _, d in cols))

        # LaTeX (one tabular per victim; booktabs)
        tex.append(f'% --- {victim} ---')
        tex.append('\\begin{tabular}{l' + 'c' * len(cols) + '}')
        tex.append('\\toprule')
        tex.append(f'\\multicolumn{{{len(cols)+1}}}{{c}}{{\\textbf{{IS-Fusion $\\rightarrow$ '
                   f'{victim}}}}} \\\\')
        tex.append('\\midrule')
        tex.append('Metric & ' + ' & '.join(labels) + ' \\\\')
        tex.append('\\midrule')
        for i, (rl, key) in enumerate(ROWS):
            bold = rl in ('mAP', 'NDS', 'Veh. mean')
            lab = f'\\textbf{{{rl}}}' if bold else rl
            cells = ' & '.join(f'{metric(d, key):.3f}' for _, d in cols)
            tex.append(f'{lab} & {cells} \\\\')
            if i == 1:
                tex.append('\\midrule')
        if clean is not None:
            dcells = ' & '.join(
                ('--' if l == 'Clean' else f'${metric(d,"veh")-metric(clean,"veh"):+.3f}$')
                for l, d in cols)
            tex.append('\\midrule')
            tex.append(f'$\\Delta$ Veh. mean & {dcells} \\\\')
        tex.append('\\bottomrule')
        tex.append('\\end{tabular}')
        if vi < len(victims) - 1:
            tex.append('\\par\\medskip')
    tex = '\n'.join(tex) + '\n'

    if args.tex:
        os.makedirs(os.path.dirname(os.path.abspath(args.tex)), exist_ok=True)
        open(args.tex, 'w').write(tex)
        print('\nwrote', args.tex)
    print('\n' + tex)


if __name__ == '__main__':
    main()
